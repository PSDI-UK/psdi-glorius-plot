const ORCID_URL_BASE = "https://orcid.org/";

/**
 * Generates the text of a metadata file based on user input
 * @param {String} title The dataset title as provided by the user
 * @param {String} desc The dataset description as provided by the user
 * @param {String} version The version of this package
 * @param {String} authorInfo The formatted author info
 * @param {String} bibInfo The formatted bibliographic info
 * @param {Boolean} reactionSchemePresent Whether or not a file is present in the crate describing the reaction scheme
 * @param {Boolean} baselineDescPresent Whether or not a file is present in the crate describing the standard conditions
 * @param {Boolean} condDescPresent Whether or not a file is present in the crate describing the different conditions
 * @returns {String} The full text of the README file
 */
export function makeMetadata(title, desc, version, authorInfo, bibInfo, reactionSchemePresent, baselineDescPresent,
	condDescPresent) {
	const timestamp = (new Date()).toISOString();

	// If the reaction scheme, baseline info, and/or condition description files are present, add lines for them
	let reactionSchemePartLine = "";
	let reactionSchemeInfo = "";
	if (reactionSchemePresent) {
		reactionSchemePartLine = `,
				{"@id": "data/reaction_scheme.cdxml"}`;
		reactionSchemeInfo = `,
		{
			"@id": "data/reaction_scheme.cdxml",
			"@type": "File",
			"name": "data/reaction_scheme.cdxml",
			"description": "ChemDraw file of the chemical transformation described by the Glorius plot.",
			"encodingFormat": "application/vnd.chemdraw+xml"
		}`;
	}
	let baselineDescPartLine = "";
	let baselineDescInfo = "";
	if (baselineDescPresent) {
		baselineDescPartLine = `,
				{"@id": "data/standard_conditions.html"}`;
		baselineDescInfo = `,
		{
			"@id": "data/reaction_scheme.cdxml",
			"@type": "File",
			"name": "data/reaction_scheme.cdxml",
			"description": "ChemDraw file of the chemical transformation described by the Glorius plot.",
			"encodingFormat": "application/vnd.chemdraw+xml"
		}`;
	}
	let condDescPartLine = "";
	let condDescInfo = "";
	if (condDescPresent) {
		condDescPartLine = `,
				{"@id": "data/test_conditions.csv"}`;
		condDescInfo = `,
		{
			"@id": "data/reaction_scheme.cdxml",
			"@type": "File",
			"name": "data/reaction_scheme.cdxml",
			"description": "ChemDraw file of the chemical transformation described by the Glorius plot.",
			"encodingFormat": "application/vnd.chemdraw+xml"
		}`;
	}

	text = `{
    "@context": "https://w3id.org/ro/crate/1.1/context",
    "@graph": [
		{
			"@id": "./",
			"@type": "Dataset",
			"name": "${title}",
			"description": "${desc}",
			"datePublished": "${timestamp}",
			"instrument": {
				"@id": "https://psdi-uk.github.io/psdi-glorius-plot/"
			},
			"hasPart": [
				{"@id": "data/plot/glorius_plot.png"},
				{"@id": "data/plot/sensitivity_table.csv"},
				{"@id": "data/plot/user_preferences.json"},
				{"@id": "ESI.pdf"},
				{"@id": "README.md"},${reactionSchemePartLine}${baselineDescPartLine}${condDescPartLine}
			],
			"mainEntity": {
                "@id": "ESI.pdf"
            }${authorInfo},
			"license": {
				"@id": "https://spdx.org/licenses/CC-BY-4.0.html"
			}
		},
		{
			"@id": "ro-crate-metadata.json",
			"@type": "CreativeWork",
			"description": "A machine-readable file describing the dataset contained within this Research Object Crate (RO-Crate).",
			"about": {
                "@id": "./"
            },
            "conformsTo": [
                {
                    "@id": "https://w3id.org/ro/crate/1.1"
                }
            ]
		},
		{
			"@id": "https://psdi-uk.github.io/psdi-glorius-plot/",
			"@type": "SoftwareApplication",
			"url": "https://psdi-uk.github.io/psdi-glorius-plot/",
			"name": "PSDI Glorius Plot Generator",
			"version": "${version}"
		},
		{
			"@id": "data/plot/glorius_plot.png",
			"@type": "File",
			"name": "data/plot/glorius_plot.png",
			"description":"Image of Glorius plot generated by PSDI Glorius Plot Generator.",
			"encodingFormat": "image/png"
		},
		{
			"@id": "data/plot/sensitivity_table.csv",
			"@type": "File",
			"name": "data/plot/sensitivity_table.csv",
			"description": "Tabulated reaction outcomes for each test condition plotted by the PSDI Plot Generator.",
			"encodingFormat": "text/csv"
		},
		{
			"@id": "data/plot/user_preferences.json",
			"@type": "File",
			"name": "data/plot/user_preferences.json",
			"description": "User preferences specified in PSDI Glorius Plot Generator.",
			"encodingFormat": "application/json"
		},
		{
			"@id": "ESI.pdf",
			"@type": "File",
			"name": "ESI.pdf", 
			"description": "A PDF electronic supplementary information file containing bibliographic information, details of the standard conditions for the experiment, preparation of the experimental conditions for the sensitivity assessment for the reaction, an image of the reaction, the results table for the sensitivity of the reaction, and the Glorius plot.",
			"encodingFormat": "application/pdf"
		},
		{
			"@id": "README.md",
			"@type": "File",
			"name": "README.md", 
			"description": "README for dataset generated by PSDI Glorius Plot Generator",
			"encodingFormat": "text/markdown"
		}${reactionSchemeInfo}${baselineDescInfo}${condDescInfo}${bibInfo},
		{
			"@id": "https://spdx.org/licenses/CC-BY-4.0.html",
			"@type": "CreativeWork",
			"name": "CC-BY-4.0"
		}
	]
}`;

	return text
}

/**
 * Formats the author and bibliographic info sections of the metadata file based on author info
 * @param {Array<Array<string>>} lNamesAndORCIDs List of name, orcID pairs
 * @returns {Array<string>} First element: The text of the Author Info section. Second element: The text of the Biblio
 *                          Info section
 */
export function formatMetadataBibInfo(lNamesAndORCIDs) {

	let authorInfo = "";
	let bibInfo = "";

	// First check if we have any info to include in this section
	if (!lNamesAndORCIDs)
		return [authorInfo, bibInfo];

	let haveSomeInfo = false;
	lNamesAndORCIDs.forEach(([name, orcId]) => {
		if (name || orcId)
			haveSomeInfo = true;
	});

	// Fill out the beginning bit of the Author Info section
	authorInfo = `,
			"author": [`;

	let firstEntry = true;
	lNamesAndORCIDs.forEach(([name, orcId]) => {

		// If no name or orcId is present, skip this entry
		if (!(name || orcId))
			return;

		// We preferentially use the ORCID as ID, but fall back to using the name if an ORCID isn't provided
		const id = orcId || name;

		// Check how the ORCID is formatted, and always print with the full URL
		if (orcId && !orcId.startsWith(ORCID_URL_BASE))
			orcId = ORCID_URL_BASE + orcId;

		// For every entry other than the first, we start with a comma before the entry in the Author Info
		if (firstEntry)
			firstEntry = false
		else
			authorInfo += ","

		// Format and add the entries to the Author and Bib Info now
		authorInfo += `
				{
					"@id": "${id}"
				}`;
		bibInfo += `,
		{
			"@id": "${id}",
			"@type": "Person",
			"name": "${name}"
		}`;

	});

	return [authorInfo, bibInfo];
}