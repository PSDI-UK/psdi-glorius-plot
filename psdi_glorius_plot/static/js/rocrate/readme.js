const ORCID_URL_BASE = "https://orcid.org/";

/**
 * Generates the text of a README file based on user input
 * @param {Object} rocrateInfo Object containing user-input data for the RO-crate output
 * @returns {String} The full text of the README file
 */
export function makeReadme(rocrateInfo) {

  // If a license is provided, add a line for it
  let licenseLine = "";
  if (rocrateInfo.licenseURL) {
    licenseLine = `

**License:** [${rocrateInfo.licenseName || rocrateInfo.licenseURL}](${rocrateInfo.licenseURL})`;
  } else if (rocrateInfo.licenseName) {
    licenseLine = `

**License:** ${rocrateInfo.licenseName}`;
  }

  // If Bibliographic info is provided, add a section header to it
  let bibInfoText = "";
  if (rocrateInfo.bibInfo.readmeInfo) {
    bibInfoText = `

## Bibliographic Information${rocrateInfo.bibInfo.readmeInfo}`;
  }

  // If the reaction scheme, baseline info, and/or condition description files are present, add lines for them
  let reactionSchemeLine = "";
  if (rocrateInfo.haveReactionScheme) {
    reactionSchemeLine = `
  - [**reaction_scheme.cdxml**](./data/reaction_scheme.cdxml): ChemDraw file of the chemical transformation described by the Glorius plot.`;
  }
  let baselineLine = "";
  if (rocrateInfo.haveBaselineDesc) {
    baselineLine = `
  - [**standard_conditions.csv**](./data/standard_conditions.csv): Standard conditions for the chemical transformation plotted by the PSDI Glorius plot Generator.`;
  }
  let condDescLine = "";
  if (rocrateInfo.haveCondDescs) {
    condDescLine = `
  - [**test_conditions.csv**](./data/test_conditions.csv): Experimental description for each test condition plotted by the PSDI Glorius Plot Generator.`;
  }

  const text = `# README

## About

**Title**: ${rocrateInfo.title}

**Description**: ${rocrateInfo.desc}

**Date Published**: ${rocrateInfo.timestamp}${licenseLine}

**About**: ${rocrateInfo.about}${bibInfoText}

## File Structure

- [**ESI.pdf**](./ESI.pdf): A PDF electronic supplementary information file containing the results table for the sensitivity of the reaction and the Glorius plot.
- **[ro-crate-metadata.json](./ro-crate-metadata.json)**: A machine-readable file describing the dataset contained within this Research Object Crate (RO-Crate).

- **data folder**:${reactionSchemeLine}${baselineLine}${condDescLine}
  - **plot folder**:
    - [**glorius_plot.png**](./data/plot/glorius_plot.png): Image of Glorius plot generated by PSDI Glorius Plot Generator.
    - [**sensitivity_table.csv**](./data/plot/sensitivity_table.csv): Tabulated reaction outcomes for each test parameter plotted by the PSDI Plot Generator.
    - [**user_preferences.json**](./data/plot/user_preferences.json): User preferences specified in PSDI Glorius Plot Generator.
`;

  return text
}

/**
 * Formats the bibliographic info section of the README.md file based on author info
 * @param {Array<Array<string>>} lNamesAndORCIDs List of name, orcID pairs
 * @param {String} contactEmail The contact email provided by the user
 * @returns {String} The text of the section
 */
export function formatReadmeBibInfo(lNamesAndORCIDs, contactEmail) {

  let text = "";

  lNamesAndORCIDs.forEach(([name, orcId]) => {

    // If no name is present, skip this entry
    if (!name)
      return;

    text += `\n\n**Name**: ${name}`

    if (!orcId)
      return;

    // Check how the ORCID is formatted, and always print with the full URL
    if (!orcId.startsWith(ORCID_URL_BASE))
      orcId = ORCID_URL_BASE + orcId;

    text += `\n\n- **ORCID**: ${orcId}`

  });

  if (contactEmail) {
    text += `\n\n**Contact**: ${contactEmail}`
  }

  return text;
}